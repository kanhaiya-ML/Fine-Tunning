def predict(texts):
  model.eval()
  encoding = tokenizer(
      texts,
      padding=True,
      truncation=True,
      max_length=64,
      return_tensors='pt'
  )
  with torch.no_grad():
    logits = model(
        encoding['input_ids'],
        encoding['attention_mask']
    )
    probabilities = torch.softmax(logits,dim=1)
    prediction_class = torch.argmax(probabilities).item()
    confidence = probabilities[0][prediction_class].item()

  print(f"Text: {texts}")
  print(f"category: {label_names[prediction_class]} ({confidence:.2%})")

