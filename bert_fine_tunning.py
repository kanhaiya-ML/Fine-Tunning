tokenizer = DistilBertTokenizer.from_pretrained('distilbert-base-uncased')

class ComplaintDataset(Dataset):
  def __init__(self,texts,labels):
    self.encodings = tokenizer(
        texts,
        padding=True,
        truncation=True,
        max_length=64,
        return_tensors='pt'
    )
    self.labels = labels

  def __len__(self):
    return len(self.labels)

  def __getitem__(self,idx):
    return {
        'input_ids':self.encodings['input_ids'][idx],
        'attention_mask':self.encodings['attention_mask'][idx],
        'label':torch.tensor(self.labels[idx],dtype=torch.long)
    }

train_Dataset = ComplaintDataset(X_train,y_train)
val_Dataset = ComplaintDataset(X_val,y_val)

train_loader = DataLoader(train_Dataset,batch_size=4,shuffle=True)
val_loader = DataLoader(val_Dataset,batch_size=4)

class ComplaintClassifier(nn.Module):
  def __init__(self):
    super().__init__()

    #Load DistilBert
    self.bert = DistilBertModel.from_pretrained('distilbert-base-uncased')

    #Freeze all BERT layers
    for param in self.bert.parameters():
      param.requires_grad = False

    self.classifier = nn.Sequential(
        nn.Linear(768,256),
        nn.ReLU(),
        nn.Dropout(0.3),
        nn.Linear(256,3)
    )

  def forward(self,input_ids,attention_mask):
    outputs = self.bert(
        input_ids = input_ids,
        attention_mask = attention_mask,
    )
    cls_output = outputs.last_hidden_state[:,0,:]

    logits = self.classifier(cls_output)
    return logits

model = ComplaintClassifier()

total = sum(p.numel() for p in model.parameters())
trainable = sum(p.numel() for p in model.parameters() if p.requires_grad)
frozen = total - trainable

print(f"Total: {total}")
print(f"Trainable Parameters: {trainable}")
print(f"frozen parameters: {frozen}")

criterion = nn.CrossEntropyLoss()
optimizer = torch.optim.Adam(
    filter(lambda p:p.requires_grad,model.parameters()),
    lr=0.001
)
def train_epoch():
  model.train()
  total_loss=0
  correct=0

  for batch in train_loader:
    input_ids = batch['input_ids']
    attention_mask = batch['attention_mask']
    labels = batch['label']

    logits = model(input_ids,attention_mask)
    loss = criterion(logits,labels)

    optimizer.zero_grad()
    loss.backward()
    optimizer.step()

    total_loss += loss.item()
    predictions = torch.argmax(logits,dim=1)
    correct += (predictions == labels).sum().item()

  return total_loss/len(train_loader),correct/len(X_train)

def evaluate():
  model.eval()
  correct = 0

  with torch.no_grad():
    for batch in val_loader:
      input_ids = batch['input_ids']
      attention_mask = batch['attention_mask']
      labels = batch['label']

      logits = model(input_ids,attention_mask)
      predictions = torch.argmax(logits,dim=1)
      correct += (predictions==labels).sum().item()
  return correct/len(X_val)

#Train
for epoch in range(20):
    train_loss, train_acc = train_epoch()
    val_acc = evaluate()
    print(f"Epoch {epoch+1:2d} | Loss: {train_loss:.4f} | Train Acc: {train_acc:.2%} | Val Acc: {val_acc:.2%}")

